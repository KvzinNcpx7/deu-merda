// Append a content-only revision; never rewrite an existing schema migration.
import { readFileSync, writeFileSync } from "node:fs";
const cards = JSON.parse(readFileSync("src/data/cards.json", "utf8"));
const baseline = readFileSync(
  "supabase/migrations/202610280003_humor.sql",
  "utf8",
);
const quote = (s) => `'${s.replaceAll("'", "''")}'`;
const rows = cards
  .map(
    (c) =>
      `(${[c.id, c.text, c.pack].map(quote).join(",")},${c.pick},${[c.theme, c.tone, c.grammar].map(quote).join(",")})`,
  )
  .filter((row) => !baseline.includes(row));
if (!rows.length)
  throw new Error("Nenhuma revisão de conteúdo em relação à migração 003.");
writeFileSync(
  "supabase/migrations/202610290004_editorial.sql",
  `-- Generated by scripts/generate-catalog-update.mjs; original cards, editorial revision.
-- Existing room JSON, hands, scores and custom cards remain untouched.
begin;
insert into private.cards(id,text,pack,pick,theme,tone,grammar) values
${rows.join(",\n")}
on conflict (id) do update set text=excluded.text,pack=excluded.pack,pick=excluded.pick,theme=excluded.theme,tone=excluded.tone,grammar=excluded.grammar;
commit;
`,
);
