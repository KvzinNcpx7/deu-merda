// Regenerate only migration 003 before its first application. Later releases need a new migration.
import { readFileSync, writeFileSync } from "node:fs";
const cards = JSON.parse(readFileSync("src/data/cards.json", "utf8"));
const themes = JSON.parse(readFileSync("src/data/themes.json", "utf8"));
const original = readFileSync(
  "supabase/migrations/202610280001_game.sql",
  "utf8",
);
const quote = (s) => `'${s.replaceAll("'", "''")}'`;
function definition(name) {
  const start = original.indexOf(`create function private.${name}(`);
  const end = original.indexOf("end $$;", start) + "end $$;".length;
  if (start < 0 || end < start) throw new Error(`Missing ${name}`);
  return original
    .slice(start, end)
    .replace("create function", "create or replace function");
}
const themeFilter =
  " and not coalesce(r->'excludedThemes','[]'::jsonb) ? c.theme";
const refill = definition("refill").replace(
  "and r->'packs' ? c.pack",
  "and r->'packs' ? c.pack" + themeFilter,
);
const round = definition("new_round").replace(
  "and r->'packs' ? c.pack",
  "and r->'packs' ? c.pack" + themeFilter,
);
const themeList = Object.keys(themes).map(quote).join(",");
let apply = definition("apply_game").replace(
  "x not in ('quinta','brasil','escola','economia','memes')",
  "x not in ('quinta','brasil','escola','economia','memes','acido')",
);
apply = apply.replace(
  " when 'custom','editCustom' then",
  ` if p_action ? 'excludedThemes' then
 if jsonb_typeof(p_action->'excludedThemes') is distinct from 'array' then raise exception 'Temas inválidos.';end if;
 if exists(select 1 from jsonb_array_elements(p_action->'excludedThemes') x where jsonb_typeof(x)<>'string' or trim(both '"' from x::text) not in (${themeList})) then raise exception 'Temas inválidos.';end if;
 r:=jsonb_set(r,'{excludedThemes}',p_action->'excludedThemes');
 end if;
 when 'custom','editCustom' then`,
);
const rows = cards
  .map(
    (c) =>
      `(${[c.id, c.text, c.pack].map(quote).join(",")},${c.pick},${[c.theme, c.tone, c.grammar].map(quote).join(",")})`,
  )
  .join(",\n");
const sql = `-- Generated by scripts/generate-catalog-migration.mjs. Catálogo autoral v2.
-- Preserve salas, mãos, pontuação e cartas personalizadas existentes.
begin;
alter table private.cards add column theme text, add column tone text, add column grammar text;
insert into private.cards(id,text,pack,pick,theme,tone,grammar) values
${rows}
on conflict (id) do update set text=excluded.text,pack=excluded.pack,pick=excluded.pick,theme=excluded.theme,tone=excluded.tone,grammar=excluded.grammar;

${refill}

${round}

${apply}

-- CREATE OR REPLACE conserva grants; explicita novamente a restrição das funções alteradas.
revoke all on function private.refill(jsonb), private.new_round(jsonb), private.apply_game(text,jsonb) from public, anon, authenticated;
commit;
`;
writeFileSync("supabase/migrations/202610280003_humor.sql", sql);
